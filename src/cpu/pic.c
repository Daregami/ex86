#include "cpu/ports.h"

void pic_remap() {
    outb(0x20,0x11);    // ICW1
    outb(0x80,0);
    outb(0x21,0x20);    // ICW2
    outb(0x80,0);
    outb(0x21,1 << 2);  // ICW3
    outb(0x80,0);
    outb(0x21,0x01);    // ICW4
    outb(0x80,0);
    outb(0x21,0b11111100);
    outb(0x80,0);
    
    outb(0xA0,0x11);
    outb(0x80,0);
    outb(0xA1,0x28);
    outb(0x80,0);
    outb(0xA1,0x02);
    outb(0x80,0);
    outb(0xA1,0x01);
    outb(0x80,0);
    outb(0xA1,0b11111111);
    outb(0x80,0);
}